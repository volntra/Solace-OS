#!/usr/bin/env python3
"""Generates the Solace logo SVGs in assets/brand/.

The artwork is original: a sun settling into still water at dusk, on our
continuous-curvature squircle plate. Run `just logo` to regenerate and
render PNG previews.

Outputs:
  assets/brand/solace-icon.svg   full-colour app-style icon (1024 x 1024)
  assets/brand/solace-mark.svg   single-colour mark (currentColor), for the
                                 menu bar, boot splash, and GRUB theme
"""

import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parents[2] / "assets" / "brand"

# --- The squircle --------------------------------------------------------
# A superellipse |x/a|^n + |y/a|^n = 1. n = 5 gives the continuous-curvature
# corner (no visible point where the straight edge meets the curve).
# de/design will own this definition from Phase 6; keep them identical.
SQUIRCLE_EXPONENT = 5.0
CANVAS = 1024
PLATE = 824  # leaves room for the drop shadow, as app icons do
SAMPLES = 720


def squircle_path(cx, cy, size, n=SQUIRCLE_EXPONENT, samples=SAMPLES):
    a = size / 2
    pts = []
    for i in range(samples):
        t = 2 * math.pi * i / samples
        c, s = math.cos(t), math.sin(t)
        x = cx + a * math.copysign(abs(c) ** (2 / n), c)
        y = cy + a * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{x:.2f} {y:.2f}")
    return "M" + " L".join(pts) + " Z"


# --- Scene geometry ------------------------------------------------------
C = CANVAS / 2
TOP = C - PLATE / 2
BOTTOM = C + PLATE / 2
HORIZON = 584
SUN_R = 184
# Reflection ripples: (y offset below horizon, width, height, opacity)
RIPPLES = [(30, 360, 26, 0.95), (76, 268, 22, 0.72), (118, 184, 18, 0.5),
           (154, 110, 15, 0.32), (184, 54, 12, 0.18)]
# The single-colour mark keeps only the first three, drawn bolder, so it
# still reads at 16 px in the menu bar.
# Every edge sits on a 4-unit grid: exactly one pixel at 16 px.
MARK_RIPPLES = [(6, 48, 4), (14, 32, 4), (22, 16, 4)]


def ripples_svg(fill, scale=1.0, cx=C, horizon=HORIZON, opacity=True):
    out = []
    for dy, w, h, op in RIPPLES:
        w, h, dy = w * scale, h * scale, dy * scale
        x = cx - w / 2
        y = horizon + dy
        o = f' opacity="{op}"' if opacity else ""
        out.append(
            f'<rect x="{x:.2f}" y="{y:.2f}" width="{w:.2f}" height="{h:.2f}" '
            f'rx="{h / 2:.2f}" fill="{fill}"{o}/>'
        )
    return "\n    ".join(out)


def icon_svg():
    plate = squircle_path(C, C, PLATE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
  <title>Solace</title>
  <!-- Original artwork for Solace. Generated by tools/brand/gen-logo.py; edit that, not this. -->
  <defs>
    <clipPath id="plate"><path d="{plate}"/></clipPath>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="22"/>
      <feOffset dy="14"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.32"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <linearGradient id="sky" x1="0" y1="{TOP}" x2="0" y2="{HORIZON}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#16184A"/>
      <stop offset="0.4" stop-color="#3A3088"/>
      <stop offset="0.78" stop-color="#B05C8E"/>
      <stop offset="1" stop-color="#F7A072"/>
    </linearGradient>
    <linearGradient id="water" x1="0" y1="{HORIZON}" x2="0" y2="{BOTTOM}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#3A3384"/>
      <stop offset="0.45" stop-color="#232262"/>
      <stop offset="1" stop-color="#121338"/>
    </linearGradient>
    <radialGradient id="glow" cx="{C}" cy="{HORIZON}" r="360" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFD39A" stop-opacity="0.75"/>
      <stop offset="0.45" stop-color="#FF9F7A" stop-opacity="0.28"/>
      <stop offset="1" stop-color="#FF9F7A" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="sun" x1="0" y1="{HORIZON - SUN_R}" x2="0" y2="{HORIZON}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFF4D2"/>
      <stop offset="0.55" stop-color="#FFD58C"/>
      <stop offset="1" stop-color="#FFAA5C"/>
    </linearGradient>
    <linearGradient id="ripple" x1="0" y1="{HORIZON}" x2="0" y2="{HORIZON + 210}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFD08A"/>
      <stop offset="1" stop-color="#FF9E6E"/>
    </linearGradient>
    <linearGradient id="gloss" x1="0" y1="{TOP}" x2="0" y2="{C}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.07"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
    <linearGradient id="haze" x1="0" y1="{HORIZON - 26}" x2="0" y2="{HORIZON + 26}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFE2B8" stop-opacity="0"/>
      <stop offset="0.5" stop-color="#FFE2B8" stop-opacity="0.55"/>
      <stop offset="1" stop-color="#FFE2B8" stop-opacity="0"/>
    </linearGradient>
  </defs>

  <g filter="url(#shadow)">
    <path d="{plate}" fill="#121338"/>
  </g>
  <g clip-path="url(#plate)">
    <rect x="0" y="0" width="{CANVAS}" height="{HORIZON}" fill="url(#sky)"/>
    <rect x="0" y="{HORIZON}" width="{CANVAS}" height="{CANVAS - HORIZON}" fill="url(#water)"/>
    <circle cx="{C}" cy="{HORIZON}" r="360" fill="url(#glow)"/>
    <!-- the sun, half set -->
    <path d="M{C - SUN_R} {HORIZON} A{SUN_R} {SUN_R} 0 0 1 {C + SUN_R} {HORIZON} Z" fill="url(#sun)"/>
    <rect x="0" y="{HORIZON - 26}" width="{CANVAS}" height="52" fill="url(#haze)"/>
    <!-- its reflection on still water -->
    {ripples_svg("url(#ripple)")}
    <rect x="0" y="0" width="{CANVAS}" height="{C}" fill="url(#gloss)"/>
  </g>
  <path d="{plate}" fill="none" stroke="#FFFFFF" stroke-opacity="0.14" stroke-width="3"/>
</svg>
"""


def mark_svg():
    # 64 x 64, single colour, centred optically: half sun over three ripples.
    size = 64
    cx = size / 2
    horizon = 28
    r = 16
    bars = []
    for dy, w, h in MARK_RIPPLES:
        bars.append(
            f'<rect x="{cx - w / 2:.2f}" y="{horizon + dy - h / 2:.2f}" width="{w:.2f}" '
            f'height="{h:.2f}" rx="{h / 2:.2f}" fill="currentColor"/>'
        )
    bars_svg = "\n  ".join(bars)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">
  <title>Solace</title>
  <!-- Original artwork for Solace. Generated by tools/brand/gen-logo.py; edit that, not this. -->
  <path d="M{cx - r:.2f} {horizon} A{r:.2f} {r:.2f} 0 0 1 {cx + r:.2f} {horizon} Z" fill="currentColor"/>
  {bars_svg}
</svg>
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "solace-icon.svg").write_text(icon_svg())
    (OUT / "solace-mark.svg").write_text(mark_svg())
    print(f"wrote {OUT}/solace-icon.svg and solace-mark.svg")


if __name__ == "__main__":
    main()
