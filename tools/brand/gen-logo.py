#!/usr/bin/env python3
"""Generates the Fern logo SVGs in assets/brand/.

The artwork is original: a simple pine tree (a soft cone with two branch
cuts) on our continuous-curvature squircle plate. Run `just logo` to regenerate and
render PNG previews.

Outputs:
  assets/brand/fern-icon.svg   full-colour app-style icon (1024 x 1024)
  assets/brand/fern-mark.svg   single-colour mark (currentColor), for the
                                 menu bar, boot splash, and GRUB theme
  assets/brand/fern-icon-glass.svg
                                 clear glass variant on a transparent
                                 background (the reference for the "Clear"
                                 icon mode, CLAUDE.md 6.9)
  build/brand/glass-preview.svg  the glass icon over sample backdrops, for
                                 judging translucency (not shipped)
"""

import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parents[2] / "assets" / "brand"

# --- The squircle --------------------------------------------------------
# A superellipse |x/a|^n + |y/a|^n = 1. n = 5 gives the continuous-curvature
# corner (no visible point where the straight edge meets the curve).
# de/design will own this definition from Phase 6; keep them identical.
SQUIRCLE_EXPONENT = 5.0
CANVAS = 1024
PLATE = 824  # leaves room for the drop shadow, as app icons do
SAMPLES = 720


def squircle_path(cx, cy, size, n=SQUIRCLE_EXPONENT, samples=SAMPLES):
    a = size / 2
    pts = []
    for i in range(samples):
        t = 2 * math.pi * i / samples
        c, s = math.cos(t), math.sin(t)
        x = cx + a * math.copysign(abs(c) ** (2 / n), c)
        y = cy + a * math.copysign(abs(s) ** (2 / n), s)
        pts.append(f"{x:.2f} {y:.2f}")
    return "M" + " L".join(pts) + " Z"


# --- The tree ------------------------------------------------------------
# A single soft cone with two branch cuts and a trunk, drawn on a 64-unit
# grid (the mark's own size) and scaled up for the icons. The cuts are
# narrow wedges that reach in towards the trunk; a thin round-joined
# stroke of the same colour softens every corner.
TREE_CX = 32
APEX, BASE, HALF = 6, 48, 18          # cone: apex y, base y, half-width
CUTS = [(20, 4.2), (33, 4.2)]         # (y where a cut starts, its opening)
CUT_DEPTH = 2.2                        # half-width left at a cut's inner end
STROKE = 1.2
TRUNK = (29, 47, 6, 11)               # x, y, w, h


def tree_path(cx=TREE_CX):
    def edge(y):
        return HALF * (y - APEX) / (BASE - APEX)
    right = [(cx, APEX)]
    for y, opening in CUTS:
        right += [(cx + edge(y), y), (cx + CUT_DEPTH, y + opening * 0.38),
                  (cx + edge(y + opening), y + opening)]
    right.append((cx + HALF, BASE))
    left = [(2 * cx - x, y) for x, y in reversed(right[1:])]
    pts = right + left
    return "M" + "L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + "Z"


def tree_svg(fill, attrs=""):
    """The tree in 64-unit coordinates."""
    x, y, w, h = TRUNK
    return (f'<path d="{tree_path()}" fill="{fill}" stroke="{fill}" stroke-width="{STROKE}" '
            f'stroke-linejoin="round"{attrs}/>'
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="1.5" fill="{fill}"{attrs}/>')


# On the 1024 icon canvas the 64-unit tree is drawn this much larger,
# centred on the plate.
C = CANVAS / 2
TOP = C - PLATE / 2
BOTTOM = C + PLATE / 2
TREE_SCALE = 8.5
TREE_ORIGIN = C - TREE_CX * TREE_SCALE


def icon_svg():
    plate = squircle_path(C, C, PLATE)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
  <title>Fern</title>
  <!-- Original artwork for Fern. Generated by tools/brand/gen-logo.py; edit that, not this. -->
  <defs>
    <clipPath id="plate"><path d="{plate}"/></clipPath>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="22"/>
      <feOffset dy="14"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.32"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <filter id="lift" x="-30%" y="-30%" width="160%" height="160%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="1.1"/>
      <feOffset dy="0.9"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.28"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <linearGradient id="green" x1="0" y1="{TOP}" x2="0" y2="{BOTTOM}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#3B8F5E"/>
      <stop offset="0.55" stop-color="#2F7A50"/>
      <stop offset="1" stop-color="#173D2E"/>
    </linearGradient>
    <radialGradient id="light" cx="{C}" cy="{TOP + 60}" r="560" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#E3F0E4" stop-opacity="0.22"/>
      <stop offset="1" stop-color="#E3F0E4" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="gloss" x1="0" y1="{TOP}" x2="0" y2="{C}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.07"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </linearGradient>
  </defs>

  <g filter="url(#shadow)">
    <path d="{plate}" fill="#10291F"/>
  </g>
  <g clip-path="url(#plate)">
    <rect x="0" y="0" width="{CANVAS}" height="{CANVAS}" fill="url(#green)"/>
    <rect x="0" y="0" width="{CANVAS}" height="{CANVAS}" fill="url(#light)"/>
    <g transform="translate({TREE_ORIGIN} {TREE_ORIGIN}) scale({TREE_SCALE})" filter="url(#lift)">
      {tree_svg("#F6F7F3")}
    </g>
    <rect x="0" y="0" width="{CANVAS}" height="{C}" fill="url(#gloss)"/>
  </g>
  <path d="{plate}" fill="none" stroke="#FFFFFF" stroke-opacity="0.14" stroke-width="3"/>
</svg>
"""


def glass_svg():
    """Clear glass: a translucent, lightly frosted plate that lets the
    backdrop through, lit along its rim, with a white tree.

    A standalone SVG cannot blur what is behind it; on screen the
    compositor adds the backdrop blur (the "Clear" icon mode).
    """
    plate = squircle_path(C, C, PLATE)
    inset = squircle_path(C, C, PLATE - 28)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{CANVAS}" height="{CANVAS}" viewBox="0 0 {CANVAS} {CANVAS}">
  <title>Fern</title>
  <!-- Original artwork for Fern. Generated by tools/brand/gen-logo.py; edit that, not this. -->
  <defs>
    <clipPath id="g-plate"><path d="{plate}"/></clipPath>
    <filter id="g-shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="26"/>
      <feOffset dy="18"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.22"/></feComponentTransfer>
    </filter>
    <filter id="g-lift" x="-30%" y="-30%" width="160%" height="160%">
      <feGaussianBlur in="SourceAlpha" stdDeviation="1.2"/>
      <feOffset dy="0.95"/>
      <feComponentTransfer><feFuncA type="linear" slope="0.30"/></feComponentTransfer>
      <feMerge><feMergeNode/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <filter id="g-soft" x="-10%" y="-10%" width="120%" height="120%">
      <feGaussianBlur stdDeviation="9"/>
    </filter>
    <!-- the glass body: brighter where light enters (top left) -->
    <linearGradient id="g-body" x1="{TOP}" y1="{TOP}" x2="{BOTTOM}" y2="{BOTTOM}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.26"/>
      <stop offset="0.5" stop-color="#FFFFFF" stop-opacity="0.07"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0.13"/>
    </linearGradient>
    <!-- a cool tint so the glass reads on white backgrounds too -->
    <linearGradient id="g-tint" x1="0" y1="{TOP}" x2="0" y2="{BOTTOM}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#9FE0B0" stop-opacity="0.08"/>
      <stop offset="1" stop-color="#173D2E" stop-opacity="0.16"/>
    </linearGradient>
    <!-- rim light: catches on the top-left and bottom-right edges -->
    <linearGradient id="g-rim" x1="{TOP}" y1="{TOP}" x2="{BOTTOM}" y2="{BOTTOM}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.95"/>
      <stop offset="0.28" stop-color="#FFFFFF" stop-opacity="0.25"/>
      <stop offset="0.55" stop-color="#FFFFFF" stop-opacity="0.06"/>
      <stop offset="0.82" stop-color="#FFFFFF" stop-opacity="0.30"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0.80"/>
    </linearGradient>
    <radialGradient id="g-sheen" cx="{C - 120}" cy="{TOP + 40}" r="520" gradientUnits="userSpaceOnUse"
                    gradientTransform="translate(0 {TOP + 40}) scale(1 0.45) translate(0 {-(TOP + 40)})">
      <stop offset="0" stop-color="#FFFFFF" stop-opacity="0.40"/>
      <stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <path d="{plate}" fill="#000000" filter="url(#g-shadow)"/>
  <g clip-path="url(#g-plate)">
    <path d="{plate}" fill="url(#g-tint)"/>
    <path d="{plate}" fill="url(#g-body)"/>
    <rect x="0" y="0" width="{CANVAS}" height="{C}" fill="url(#g-sheen)"/>
    <!-- glass thickness: a soft light band just inside the edge -->
    <path d="{inset}" fill="none" stroke="#FFFFFF" stroke-opacity="0.22" stroke-width="10" filter="url(#g-soft)"/>
    <g transform="translate({TREE_ORIGIN} {TREE_ORIGIN}) scale({TREE_SCALE})" filter="url(#g-lift)">
      {tree_svg("#FFFFFF")}
    </g>
  </g>
  <!-- hairline just outside the rim, so the edge holds on white -->
  <path d="{plate}" fill="none" stroke="#10291F" stroke-opacity="0.12" stroke-width="3"/>
  <!-- rim: a centred stroke clipped to the plate leaves only its inner half -->
  <g clip-path="url(#g-plate)">
    <path d="{plate}" fill="none" stroke="url(#g-rim)" stroke-width="9"/>
  </g>
</svg>
"""


def glass_preview_svg(glass):
    """The glass icon over a colourful wallpaper, white, and near-black,
    to judge how it reads on each."""
    w, h, icon = 1800, 700, 460
    nested = glass.replace("<svg ", "<svg x=\"{x}\" y=\"120\" ", 1).replace(
        f'width="{CANVAS}" height="{CANVAS}"', f'width="{icon}" height="{icon}"', 1)
    # Each nested copy needs its own ids.
    copies = []
    for i, x in enumerate((70, 670, 1270)):
        c = nested.replace("{x}", str(x)).replace("g-", f"p{i}-")
        copies.append(c)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">
  <defs>
    <linearGradient id="wall" x1="0" y1="0" x2="600" y2="700" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="#0E2A1F"/><stop offset="0.5" stop-color="#2F7A50"/>
      <stop offset="1" stop-color="#C9E4C5"/>
    </linearGradient>
    <filter id="blob"><feGaussianBlur stdDeviation="30"/></filter>
  </defs>
  <rect x="0" y="0" width="600" height="{h}" fill="url(#wall)"/>
  <g filter="url(#blob)">
    <circle cx="150" cy="200" r="130" fill="#3BC9DB"/>
    <circle cx="460" cy="470" r="150" fill="#FFD43B"/>
    <circle cx="420" cy="140" r="90" fill="#FF6B6B"/>
  </g>
  <rect x="600" y="0" width="600" height="{h}" fill="#F4F4F7"/>
  <rect x="1200" y="0" width="600" height="{h}" fill="#141418"/>
  {"".join(copies)}
</svg>
"""


def mark_svg():
    # 64 x 64, single colour: the tree alone.
    size = 64
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">
  <title>Fern</title>
  <!-- Original artwork for Fern. Generated by tools/brand/gen-logo.py; edit that, not this. -->
  {tree_svg("currentColor")}
</svg>
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "fern-icon.svg").write_text(icon_svg())
    (OUT / "fern-mark.svg").write_text(mark_svg())
    glass = glass_svg()
    (OUT / "fern-icon-glass.svg").write_text(glass)
    preview_dir = OUT.parents[1] / "build" / "brand"
    preview_dir.mkdir(parents=True, exist_ok=True)
    (preview_dir / "glass-preview.svg").write_text(glass_preview_svg(glass))
    print(f"wrote {OUT}/fern-icon.svg, fern-mark.svg, fern-icon-glass.svg")


if __name__ == "__main__":
    main()
