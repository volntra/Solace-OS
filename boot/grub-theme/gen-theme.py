#!/usr/bin/env python3
"""Generates the Fern GRUB theme: theme.txt and the SVG pieces of its
boxes (rendered by build.sh).

Layout (percentages of the screen, so it works at any resolution):
  logo        glass icon, centred, 12% from the top
  name        "Fern", under the logo
  heading     "Choose a system to start", above the menu
  boot menu   centred, 640 px wide, on its own frosted panel, a green
              bar on the selected system,
              a thin scrollbar when the list is longer than the panel
  countdown   a bar emptying under the panel, reading "Starting the
              selected system in N seconds" (only while a timeout runs)
  keys        bottom: the keys GRUB understands here

No GRUB branding: the title is empty and GRUB's own help text is replaced
by our key line.
"""

import pathlib
import sys

# Palette (docs/design/HIG.md "Brand").
ITEM = "#DCEBDD"
ITEM_SELECTED = "#FFFFFF"
HEADING = "#B9CFBF"
HINT = "#C2D6C6"
COUNTDOWN = "#D6E6D8"
FOREST = "#0F2018"
FERN = "#2F7A50"
LEAF = "#7CC48A"

# GRUB draws a pixmap box's borders *outside* the item, so item_spacing
# must be at least 2 * RADIUS or a highlight overlaps its neighbours.
RADIUS = 10
PANEL_RADIUS = 18
LOGO = 128
MENU_W = 640


def theme_txt():
    half = MENU_W // 2
    return f"""# Fern boot menu. Generated by boot/grub-theme/gen-theme.py.
title-text: ""
desktop-image: "background.png"
desktop-image-scale-method: "crop"
desktop-color: "{FOREST}"
terminal-font: "Inter Regular 16"
terminal-box: "terminal_box_*.png"
terminal-left: "12%"
terminal-top: "18%"
terminal-width: "76%"
terminal-height: "64%"
terminal-border: "0"

+ image {{
  left = 50%-{LOGO // 2}
  top = 11%
  width = {LOGO}
  height = {LOGO}
  file = "logo.png"
}}

+ label {{
  left = 0
  top = 11%+{LOGO + 14}
  width = 100%
  height = 32
  align = "center"
  color = "{ITEM_SELECTED}"
  font = "Inter SemiBold 24"
  text = "Fern"
}}

# The heading above the menu; the menu draws its own frosted panel
# (menu_pixmap_style), under its items.
+ label {{
  left = 50%-{half}
  top = 37%+8
  width = {MENU_W}
  height = 22
  align = "left"
  color = "{HEADING}"
  font = "Inter Regular 16"
  text = "Choose a system to start"
}}

+ boot_menu {{
  left = 50%-{half}
  top = 37%+52
  width = {MENU_W}
  height = 40%-52
  item_font = "Inter Regular 20"
  selected_item_font = "Inter Regular 20"
  item_color = "{ITEM}"
  selected_item_color = "{ITEM_SELECTED}"
  item_height = 42
  item_padding = 20
  item_spacing = {2 * RADIUS + 6}
  icon_width = 0
  icon_height = 0
  item_icon_space = 0
  selected_item_pixmap_style = "select_*.png"
  menu_pixmap_style = "panel_*.png"
  scrollbar = true
  scrollbar_width = 6
  scrollbar_frame = "scrollbar_frame_*.png"
  scrollbar_thumb = "scrollbar_thumb_*.png"
}}

# Countdown: a bar that empties, with the words on it (GRUB gives a
# progress bar at least a line of text's height).
+ progress_bar {{
  id = "__timeout__"
  left = 50%-{half}
  top = 83%
  width = {MENU_W}
  height = 28
  show_text = true
  font = "Inter Regular 16"
  text = "Starting the selected system in %d seconds"
  text_color = "#FFFFFF"
  fg_color = "{FERN}"
  bg_color = "#24382D"
  border_color = "#4B6656"
}}

+ label {{
  left = 0
  top = 92%
  width = 100%
  height = 24
  align = "center"
  color = "{HINT}"
  font = "Inter Regular 16"
  text = "↑ ↓  choose      Enter  start      E  edit the entry      C  command line"
}}
"""


def rounded_box(fill, fill_opacity, stroke, stroke_opacity, r=RADIUS):
    """A 3r x 3r rounded rectangle; each 9-slice piece is a viewBox window
    onto it, so all nine pieces line up exactly."""
    size = 3 * r
    return (f'<rect x="0.75" y="0.75" width="{size - 1.5}" height="{size - 1.5}" rx="{r - 0.75}" '
            f'fill="{fill}" fill-opacity="{fill_opacity}" stroke="{stroke}" '
            f'stroke-opacity="{stroke_opacity}" stroke-width="1.5"/>')


def nine_slice(prefix, shape, r=RADIUS):
    # name: (x, y, w, h) in the 3r x 3r box
    parts = {
        "nw": (0, 0, r, r), "n": (r, 0, 1, r), "ne": (2 * r, 0, r, r),
        "w": (0, r, r, 1), "c": (r, r, 1, 1), "e": (2 * r, r, r, 1),
        "sw": (0, 2 * r, r, r), "s": (r, 2 * r, 1, r), "se": (2 * r, 2 * r, r, r),
    }
    out = {}
    for name, (x, y, w, h) in parts.items():
        out[f"{prefix}_{name}"] = (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="{x} {y} {w} {h}">{shape}</svg>\n')
    return out


def main():
    out = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "build/grub-theme/svg")
    out.mkdir(parents=True, exist_ok=True)
    (out / "theme.txt").write_text(theme_txt())
    pieces = {}
    pieces.update(nine_slice("select", rounded_box(FERN, 0.72, LEAF, 0.55)))
    pieces.update(nine_slice("terminal_box", rounded_box("#0B1A13", 0.82, "#FFFFFF", 0.18)))
    pieces.update(nine_slice("scrollbar_frame", rounded_box("#FFFFFF", 0.10, "#FFFFFF", 0.0, r=3), r=3))
    pieces.update(nine_slice("scrollbar_thumb", rounded_box("#FFFFFF", 0.55, "#FFFFFF", 0.0, r=3), r=3))
    pieces.update(nine_slice("panel", rounded_box("#0B1A13", 0.46, "#FFFFFF", 0.16, r=PANEL_RADIUS),
                             r=PANEL_RADIUS))
    for name, svg in pieces.items():
        (out / f"{name}.svg").write_text(svg)
    print(f"wrote theme.txt and {len(pieces)} pieces to {out}")


if __name__ == "__main__":
    main()
