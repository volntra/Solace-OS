FERN_MARK = os.path.join(REPO, "assets/symbols/fern/fern-mark.svg")

HEAD = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024">'
NOTE = "<!-- Generated by de/icons/set/gen-icons.py; edit that, not this. -->"


# --- Shared pieces -----------------------------------------------------


def svg(body, defs=""):
    d = f"<defs>{defs}</defs>" if defs else ""
    return f"{HEAD}\n{NOTE}\n{d}\n{body}\n</svg>\n"


def background(top, bottom, sheen=0.16):
    """A vertical gradient over the square, lighter at the top, with a
    soft light from above."""
    defs = (
        f'<linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">'
        f'<stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/></linearGradient>'
        f'<radialGradient id="sheen" cx="512" cy="40" r="760" gradientUnits="userSpaceOnUse">'
        f'<stop offset="0" stop-color="#FFFFFF" stop-opacity="{sheen}"/>'
        f'<stop offset="1" stop-color="#FFFFFF" stop-opacity="0"/></radialGradient>'
    )
    body = '<rect width="1024" height="1024" fill="url(#bg)"/>\n<rect width="1024" height="1024" fill="url(#sheen)"/>'
    return svg(body, defs)


SHADOW = '<filter id="shadow" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="14"/></filter>'


def shadowed(shape, dy=14, opacity=0.22):
    """A soft shadow of `shape` (an element string whose role attributes
    are dropped), drawn under it."""
    s = re.sub(r'\sdata-role="[^"]*"', "", shape)
    s = re.sub(r'(fill|stroke)="#[0-9A-Fa-f]{3,6}"', r'\1="#000000"', s)
    return f'<g filter="url(#shadow)" opacity="{opacity}" transform="translate(0 {dy})">{s}</g>'


def lucide(name, cx, cy, size, role, color, width=2.0):
    """A Lucide symbol, `size` px wide, centred on (cx, cy), stroked in a
    role's colour."""
    path = os.path.join(LUCIDE, f"{name}.svg")
    tree = ET.parse(path)
    inner = []
    for el in tree.getroot():
        tag = el.tag.split("}")[-1]
        attrs = " ".join(f'{k}="{v}"' for k, v in el.attrib.items())
        inner.append(f"<{tag} {attrs}/>")
    s = size / 24
    x, y = cx - size / 2, cy - size / 2
    return (
        f'<g data-role="{role}" fill="none" stroke="{color}" stroke-width="{width}" '
        f'stroke-linecap="round" stroke-linejoin="round" transform="translate({x:.1f} {y:.1f}) scale({s:.4f})">'
        + "".join(inner)
        + "</g>"
    )


def write(icon_id, key, roles, bg, fg, tint=None, dark=None):
    d = os.path.join(OUT, f"{icon_id}.fernicon")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "background.svg"), "w") as f:
        f.write(bg)
    with open(os.path.join(d, "foreground.svg"), "w") as f:
        f.write(fg)
    lines = ["# Generated by de/icons/set/gen-icons.py; edit that, not this.", "format = 1", f'key = "{key}"', "", "[roles]"]
    lines += [f'{k} = "{v}"' for k, v in roles.items()]
    if dark:
        lines += ["", "[dark]"] + [f'{k} = "{v}"' for k, v in dark.items()]
    if tint:
        lines += ["", "[tint]"] + [f"{k} = {str(v).lower()}" for k, v in tint.items()]
    with open(os.path.join(d, "icon.toml"), "w") as f:
        f.write("\n".join(lines) + "\n")


