def gear_path(cx, cy, teeth, r_out, r_in, hole):
    """A gear with rounded-off teeth, and a round hole (even-odd)."""
    pts = []
    step = 2 * math.pi / teeth
    for i in range(teeth):
        a = i * step
        # Root, rise, top, fall: the tooth covers ~45% of the step.
        for frac, r in ((0.0, r_in), (0.14, r_in), (0.24, r_out), (0.50, r_out), (0.60, r_in)):
            t = a + frac * step
            pts.append((cx + r * math.cos(t), cy + r * math.sin(t)))
    d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + " Z"
    d += f" M{cx + hole} {cy} A{hole} {hole} 0 1 0 {cx - hole} {cy} A{hole} {hole} 0 1 0 {cx + hole} {cy} Z"
    return d


def fern_mark(cx, cy, height, role, color):
    """The Fern tree mark (assets/symbols/fern), `height` px tall."""
    text = open(FERN_MARK).read()
    shapes = re.findall(r"<(path|rect)\s([^>]*?)/>", text)
    s = height / 52  # the mark spans y 6..58 of its 64 grid
    out = []
    for tag, attrs in shapes:
        # Colours come from the group, so the role rewrite reaches them.
        attrs = re.sub(r'\s(fill|stroke)="currentColor"', "", attrs)
        out.append(f"<{tag} {attrs}/>")
    x, y = cx - 32 * s, cy - 32 * s
    return f'<g data-role="{role}" fill="{color}" stroke="{color}" transform="translate({x:.1f} {y:.1f}) scale({s:.3f})">' + "".join(out) + "</g>"


