def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)
    apps()
    folders()
    trash()
    drives()
    files()
    n = len([d for d in os.listdir(OUT) if d.endswith(".fernicon")])
    print(f"{n} icons in {os.path.relpath(OUT, REPO)}")


if __name__ == "__main__":
    sys.exit(main())
