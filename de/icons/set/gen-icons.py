"""Generates Fern's icon set: one .fernicon directory per icon in
de/icons/set/icons/ (format: docs/formats/icon.md). Original artwork;
the small glyphs on folders, drives and documents are Lucide symbols
(ISC, assets/symbols/lucide/LICENSE).

    de/icons/set/gen-icons.py        # rewrites de/icons/set/icons/

Edit this script, not the generated files. Review the result with
`just icon-sheet` (every icon in every mode).
"""

